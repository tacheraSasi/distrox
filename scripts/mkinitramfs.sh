#!/usr/bin/env bash
# =============================================================================
# mkinitramfs.sh Pack the Alpine rootfs + Zig userland into an initramfs
#
# Usage:
#   ./scripts/mkinitramfs.sh <rootfs.tar.gz> <zig-out-bin-dir> <output> [zig-init]
#
# Steps:
#   1. Unpack the rootfs tarball into a staging dir
#   2. Copy any locally-built Zig binaries into /usr/local/bin
#   3. Generate /etc/profile.d/zig-coreutils.sh aliases for the Zig commands
#   4. If [zig-init] is provided, replace /init with the Zig PID 1 binary
#   5. Repack the whole tree as a newc cpio archive, gzip compressed
#
# Uses bsdtar for the newc archive (works on macOS and Linux; the kernel
# accepts newc without padding issues).
#
# The Zig userspace is a busybox-style multi-call binary: it dispatches on
# argv[0] OR the first argument (see userspace/src/main.zig), so interactive
# shells get the Zig commands via aliases while busybox remains the default
# for scripts. Keep ZIG_COMMANDS in sync with userspace/src/commands/listing.zig
# (commands whose `enabled` is true for Linux).
# =============================================================================

set -euo pipefail

ROOTFS_TAR="${1:?usage: mkinitramfs.sh <rootfs.tar.gz> <zig-bin-dir> <output> [init-bin]}"
ZIG_BIN_DIR="${2:-}"
OUTPUT="${3:?usage: mkinitramfs.sh <rootfs.tar.gz> <zig-bin-dir> <output> [init-bin]}"
ZIG_INIT="${4:-}"

ZIG_BIN=zig-coreutils
# Commands enabled on Linux, see userspace/src/commands/listing.zig
ZIG_COMMANDS="basename clear dirname false groups nproc touch true uname unlink whoami yes"

STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

echo "[mkinitramfs] unpacking ${ROOTFS_TAR}"
tar -xzf "${ROOTFS_TAR}" -C "${STAGE}"

# The rootfs tar omits pseudo-filesystem dirs; recreate them so OpenRC
# can mount /proc, /sys etc. at boot.
mkdir -p "${STAGE}/proc" "${STAGE}/sys" "${STAGE}/dev" "${STAGE}/run" "${STAGE}/tmp"

# Alpine installs some setuid helpers (e.g. /bin/bbsuid) execute-only;
# bsdtar needs read permission to archive them, so grant it in the
# staging copy (the packed rootfs keeps whatever mode tar stored).
find "${STAGE}" -type f ! -perm -u+r -exec chmod u+r {} +

if [[ -d "${ZIG_BIN_DIR}" ]] && compgen -G "${ZIG_BIN_DIR}/*" > /dev/null; then
    echo "[mkinitramfs] injecting Zig binaries from ${ZIG_BIN_DIR}"
    mkdir -p "${STAGE}/usr/local/bin"
    cp "${ZIG_BIN_DIR}"/* "${STAGE}/usr/local/bin/"

    if [[ -x "${STAGE}/usr/local/bin/${ZIG_BIN}" ]]; then
        echo "[mkinitramfs] writing /etc/profile.d/zig-coreutils.sh aliases"
        mkdir -p "${STAGE}/etc/profile.d"
        {
            echo "# Zig userspace aliases (generated by mkinitramfs.sh)"
            echo "# ${ZIG_BIN} dispatches on argv[0] or first argument; busybox stays the default for scripts."
            for cmd in ${ZIG_COMMANDS}; do
                echo "alias ${cmd}='${ZIG_BIN} ${cmd}'"
            done
        } > "${STAGE}/etc/profile.d/zig-coreutils.sh"
    fi
elif [[ -n "${ZIG_BIN_DIR}" ]]; then
    echo "[mkinitramfs] note: no binaries in ${ZIG_BIN_DIR} (zig build not run?)"
fi

if [[ -n "${ZIG_INIT}" && -x "${ZIG_INIT}" ]]; then
    echo "[mkinitramfs] replacing /init with Zig PID 1 (${ZIG_INIT})"
    cp "${ZIG_INIT}" "${STAGE}/init"
    chmod +x "${STAGE}/init"
fi

echo "[mkinitramfs] packing ${OUTPUT}"
( cd "${STAGE}" && bsdtar --format newc -cf - . ) | gzip -9 > "${OUTPUT}"

echo "[mkinitramfs] done: $(du -sh "${OUTPUT}" | cut -f1)"
